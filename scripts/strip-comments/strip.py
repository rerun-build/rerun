import argparse
import ast
import io
import json
import os
import re
import subprocess
import sys
import tempfile
import tokenize

TS_EXT = (".ts", ".tsx", ".mts", ".cts", ".js", ".mjs", ".cjs")
HASH_EXT = (".sh", ".yml", ".yaml", ".toml")
GENERATED = re.compile(r"auto-?generated|do not edit|generated by", re.I)
SKIP_DIRS = ("supabase/migrations/",)
PY_KEEP = re.compile(r"#\s*(noqa|type:|pragma|fmt:|ruff:|isort:|pylint:|mypy:|-\*-)")
HASH_KEEP = re.compile(r"#\s*(shellcheck|yaml-language-server|syntax=|escape=|check=)")
HEREDOC = re.compile(r"<<-?\s*(['\"]?)([A-Za-z_][A-Za-z0-9_]*)\1")


def tracked(root):
    out = subprocess.run(["git", "-C", root, "ls-files"], capture_output=True, text=True, encoding="utf-8", check=True).stdout
    return [f for f in out.split("\n") if f]


def kind(path):
    base = os.path.basename(path)
    if path.startswith(SKIP_DIRS):
        return None
    if path.endswith(TS_EXT) or re.fullmatch(r"tsconfig[\w.-]*\.json", base):
        return "ts"
    if path.endswith(".py"):
        return "py"
    if path.endswith(HASH_EXT) or base == "Dockerfile" or base.startswith("Dockerfile."):
        return "hash"
    if path.endswith(".css"):
        return "css"
    return None


def no_docstrings(tree):
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)) and node.body:
            first = node.body[0]
            if isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant) and isinstance(first.value.value, str):
                node.body = node.body[1:] or [ast.Pass()]
    return ast.dump(tree)


def strip_python(text):
    tree = ast.parse(text)
    lines = text.splitlines(keepends=True)
    drop, cut, passes = set(), {}, {}
    for tok in tokenize.generate_tokens(io.StringIO(text).readline):
        if tok.type != tokenize.COMMENT:
            continue
        row, col = tok.start
        if (row == 1 and tok.string.startswith("#!")) or PY_KEEP.match(tok.string):
            continue
        if lines[row - 1][:col].strip():
            cut[row] = col
        else:
            drop.add(row)
    for node in ast.walk(tree):
        if not isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)) or not node.body:
            continue
        first = node.body[0]
        if not (isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant) and isinstance(first.value.value, str)):
            continue
        head, tail = lines[first.lineno - 1], lines[first.end_lineno - 1]
        if head[:first.col_offset].strip() or tail[first.end_col_offset:].strip():
            continue
        rows = range(first.lineno, first.end_lineno + 1)
        if len(node.body) == 1:
            passes[first.lineno] = head[:first.col_offset] + "pass\n"
        drop.update(rows)
    out = []
    removed_last = False
    for i, line in enumerate(lines, 1):
        if i in passes:
            out.append(passes[i])
            removed_last = False
            continue
        if i in drop:
            removed_last = True
            continue
        if i in cut:
            line = line[:cut[i]].rstrip() + "\n"
        if removed_last and not line.strip() and (not out or not out[-1].strip() or out[-1].rstrip().endswith(":")):
            continue
        removed_last = False
        out.append(line)
    new = "".join(out)
    same = no_docstrings(ast.parse(text)) == ast.dump(ast.parse(new))
    return new, len(drop) + len(cut), same


def strip_hash(path, text):
    base = os.path.basename(path)
    is_sh = path.endswith(".sh")
    is_docker = base.startswith("Dockerfile")
    is_yaml = path.endswith((".yml", ".yaml"))
    lines = text.splitlines(keepends=True)
    out, removed = [], 0
    heredoc = None
    block_indent = None
    run_block = False
    quote = None
    dropped = False
    for i, line in enumerate(lines):
        stripped = line.strip()
        if heredoc:
            out.append(line)
            if stripped == heredoc:
                heredoc = None
            continue
        if is_yaml and block_indent is not None:
            indent = len(line) - len(line.lstrip(" "))
            if stripped and indent <= block_indent:
                block_indent, run_block = None, False
            else:
                if run_block and stripped.startswith("#") and not stripped.startswith("#!"):
                    removed += 1
                    continue
                out.append(line)
                continue
        comment = stripped.startswith("#") and quote is None
        keep = (i == 0 and stripped.startswith("#!")) or HASH_KEEP.match(stripped)
        if comment and not keep:
            removed += 1
            dropped = True
            continue
        if dropped and not stripped and (not out or not out[-1].strip()):
            continue
        dropped = False
        out.append(line)
        if is_sh or is_docker:
            m = HEREDOC.search(line)
            if m and quote is None:
                heredoc = m.group(2)
        if is_sh:
            quote = shell_quote_state(line, quote)
        if is_yaml:
            m = re.match(r"^(\s*)(?:-\s+)?([\w.-]+):\s*[|>][-+0-9]*\s*$", line)
            if m:
                block_indent = len(m.group(1))
                run_block = m.group(2) == "run"
    return "".join(out), removed


def shell_quote_state(line, quote):
    i = 0
    while i < len(line):
        ch = line[i]
        if quote == "'":
            if ch == "'":
                quote = None
        elif quote == '"':
            if ch == "\\":
                i += 1
            elif ch == '"':
                quote = None
        else:
            if ch == "\\":
                i += 1
            elif ch in ("'", '"'):
                quote = ch
            elif ch == "#" and (i == 0 or line[i - 1] in " \t;|&("):
                break
        i += 1
    return quote


def yaml_same(before, after):
    import yaml

    class Loader(yaml.SafeLoader):
        pass

    def tagged(loader, suffix, node):
        if isinstance(node, yaml.SequenceNode):
            return ("!" + suffix, loader.construct_sequence(node))
        if isinstance(node, yaml.MappingNode):
            return ("!" + suffix, loader.construct_mapping(node))
        return ("!" + suffix, loader.construct_scalar(node))
    Loader.add_multi_constructor("!", tagged)

    def norm(x, key=None):
        if isinstance(x, dict):
            return {k: norm(v, k) for k, v in x.items()}
        if isinstance(x, list):
            return [norm(v) for v in x]
        if key == "run" and isinstance(x, str):
            return "".join(l for l in x.splitlines(keepends=True) if not (l.strip().startswith("#") and not l.strip().startswith("#!")))
        return x
    return [norm(d) for d in yaml.load_all(before, Loader)] == [norm(d) for d in yaml.load_all(after, Loader)]


def hash_same(path, before, after):
    if path.endswith((".yml", ".yaml")):
        return yaml_same(before, after)
    if path.endswith(".toml"):
        import tomllib
        return tomllib.loads(before) == tomllib.loads(after)
    if path.endswith(".sh"):
        def ok(s):
            return subprocess.run(["bash", "-n"], input=s.replace("\r\n", "\n"), capture_output=True, text=True, encoding="utf-8").returncode == 0
        return ok(after) or not ok(before)
    return True


def strip_css(text):
    out, i, removed, quote = [], 0, 0, None
    while i < len(text):
        ch = text[i]
        if quote:
            out.append(ch)
            if ch == "\\" and i + 1 < len(text):
                out.append(text[i + 1])
                i += 2
                continue
            if ch == quote:
                quote = None
        elif ch in ("'", '"'):
            quote = ch
            out.append(ch)
        elif text.startswith("/*", i) and not text.startswith("/*!", i):
            end = text.find("*/", i + 2)
            end = len(text) if end == -1 else end + 2
            removed += 1
            out.append("\x00")
            i = end
            continue
        else:
            out.append(ch)
        i += 1
    lines, dropped = [], False
    for line in "".join(out).splitlines(keepends=True):
        if "\x00" in line and not line.replace("\x00", "").strip():
            dropped = True
            continue
        if dropped and not line.strip() and (not lines or not lines[-1].strip() or lines[-1].rstrip().endswith("{")):
            continue
        dropped = False
        lines.append(re.sub(r"[ \t]*\x00", "", line))
    return "".join(lines), removed


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=".")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--ts-module")
    ap.add_argument("--only", nargs="*", default=[])
    a = ap.parse_args()
    root = os.path.abspath(a.root)
    files = [f for f in tracked(root) if not a.only or f.startswith(tuple(a.only))]
    report = {"ts": None, "py": [0, 0, 0], "hash": [0, 0, 0], "css": [0, 0, 0], "skipped_generated": 0, "refused": []}
    ts_files = []
    for rel in files:
        k = kind(rel)
        if not k:
            continue
        path = os.path.join(root, rel)
        try:
            with open(path, encoding="utf-8", newline="") as f:
                text = f.read()
        except (UnicodeDecodeError, FileNotFoundError):
            continue
        if GENERATED.search(text[:600]):
            report["skipped_generated"] += 1
            continue
        if k == "ts":
            ts_files.append(rel)
            continue
        try:
            if k == "py":
                new, n, same = strip_python(text)
            elif k == "hash":
                new, n = strip_hash(rel, text)
                same = new == text or hash_same(rel, text, new)
            else:
                new, n = strip_css(text)
                same = True
        except (SyntaxError, tokenize.TokenError, ValueError) as e:
            report["refused"].append("%s parse: %s" % (rel, str(e)[:80]))
            continue
        report[k][0] += 1
        if new == text:
            continue
        if not same:
            report["refused"].append(rel + " shape changed")
            continue
        report[k][1] += 1
        report[k][2] += n
        if a.write:
            with open(path, "w", encoding="utf-8", newline="") as f:
                f.write(new)
    if ts_files:
        with tempfile.NamedTemporaryFile("w", delete=False, suffix=".txt", encoding="utf-8") as f:
            f.write("\n".join(ts_files))
            listing = f.name
        cmd = ["node", os.path.join(os.path.dirname(os.path.abspath(__file__)), "strip-ts.mjs"), "--root", root, "--list", listing]
        if a.ts_module:
            cmd += ["--ts", a.ts_module]
        if a.write:
            cmd.append("--write")
        res = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8")
        os.unlink(listing)
        if res.returncode:
            print(res.stderr[-2000:], file=sys.stderr)
            sys.exit(1)
        report["ts"] = json.loads(res.stdout.strip().split("\n")[-1])
        report["refused"] += report["ts"].pop("refused")
    print(json.dumps(report, indent=1))


if __name__ == "__main__":
    main()
