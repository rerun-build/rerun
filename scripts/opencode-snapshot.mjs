#!/usr/bin/env node
// Regenerates the OpenCode model snapshot the hub and the engine fall back on when the live catalog
// cannot be read. Both catalogs are public, no key needed. Run after `pnpm build:contracts`:
//
//   node scripts/opencode-snapshot.mjs
//
// The raw catalogs are kept as engine fixtures, so the parser is tested against what OpenCode
// really answered when the snapshot was taken.
import { writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { OPENCODE_CATALOG_URL, OPENCODE_PLANS, parseOpencodeCatalog } from '../packages/contracts/dist/opencode.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const fixtures = join(root, 'apps/engine/src/agents/__fixtures__/opencode')
const snapshotPath = join(root, 'packages/contracts/src/opencode-snapshot.ts')

const models = []
for (const plan of OPENCODE_PLANS) {
    const response = await fetch(OPENCODE_CATALOG_URL[plan], { signal: AbortSignal.timeout(15_000) })
    if (!response.ok) throw new Error(`${OPENCODE_CATALOG_URL[plan]} answered ${response.status}`)
    const json = await response.json()
    await writeFile(join(fixtures, `${plan}-models.json`), `${JSON.stringify(json, null, 2)}\n`)
    const parsed = parseOpencodeCatalog(json, plan)
    console.log(`${plan}: ${json.data?.length ?? 0} listed, ${parsed.length} kept`)
    models.push(...parsed)
}

const body = [
    '// Generated by `node scripts/opencode-snapshot.mjs`: do not edit by hand.',
    "import type { OpencodeModel } from './opencode.js'",
    '',
    'export const OPENCODE_SNAPSHOT: OpencodeModel[] = [',
    ...models.map(model => `    ${JSON.stringify(model)},`),
    ']',
    '',
].join('\n')
await writeFile(snapshotPath, body)
console.log(`wrote ${models.length} models to ${snapshotPath}`)
